"""
给定一个大小为 n 的数组 nums ，返回其中的多数元素。多数元素是指在数组中出现次数 大于 ⌊ n/2 ⌋ 的元素。
你可以假设数组是非空的，并且给定的数组总是存在多数元素。
"""
class Solution:#摩尔股票：推论一： 若记 众数 的票数为 +1 ，非众数 的票数为 −1 ，则一定有所有数字的 票数和 >0 。若数组的前 a 个数字的 票数和 =0 ，则 数组剩余 (n−a) 个数字的 票数和一定仍 >0 ，即后 (n−a) 个数字的 众数仍为 x 。
    def majorityElement(self, nums: list[int]) -> int:
        vote=0
        for num in nums:
            #此时num为新的众数
            if vote==0:x=num
            if num!=x:
                vote-=1
            else:
                vote+=1
        return x